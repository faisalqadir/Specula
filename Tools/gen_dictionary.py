#!/usr/bin/env python3
"""Generate Sources/DICOMCore/DictionaryData.swift from a DCMTK dicom.dic file.

Usage: python3 -I gen_dictionary.py /path/to/dicom.dic Sources/DICOMCore/DictionaryData.swift
"""
import re
import sys

src, dst = sys.argv[1], sys.argv[2]
rows = []
for line in open(src, encoding="utf-8"):
    if not line.strip() or line.startswith("#"):
        continue
    parts = line.rstrip("\n").split("\t")
    parts = [p for p in parts if p != ""]
    if len(parts) < 4:
        continue
    tag, vr, name, vm = parts[0], parts[1], parts[2], parts[3]
    version = parts[4] if len(parts) > 4 else "DICOM"
    m = re.match(r"\(([0-9A-Fa-fx\-ou]+),([0-9A-Fa-fx\-]+)\)", tag)
    if not m:
        continue
    g, e = m.group(1), m.group(2)
    if '"' in g or "PRIVATE" in version.upper():
        continue
    # Repeating groups like 6000-60FF -> 60xx; element ranges like 1000-1FFF are rare and skipped
    if "-" in g:
        lo = g.split("-")[0]
        g = lo[:2] + "xx"
    if "-" in e:
        continue
    retired = "RET" in version.upper()
    rows.append(f"{g.upper().replace('XX','xx')}{e.upper()}\t{vr}\t{name}\t{vm}\t{'R' if retired else ''}")

with open(dst, "w", encoding="utf-8") as out:
    out.write("// Generated by Tools/gen_dictionary.py from the DCMTK data dictionary (dicom.dic).\n")
    out.write("// DCMTK dicom.dic: Copyright (C) 1994-2022, OFFIS e.V. All rights reserved.\n")
    out.write("// Redistributed under the DCMTK BSD-style license; see docs/THIRD-PARTY.md.\n\n")
    out.write("// swiftlint:disable all\n")
    out.write("let dictionaryTable: String = #\"\"\"\n")
    for r in rows:
        out.write(r + "\n")
    out.write("\"\"\"#\n")
print(f"{len(rows)} entries", file=sys.stderr)
